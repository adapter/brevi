import { rm } from "node:fs/promises";
import { join } from "node:path";
import { WORKSPACES_DIR, type FirecrackerConfig } from "@brevi/shared";
import { fileExists, isReadWritable, resolveBinary } from "../host.js";
import type { CreateSandboxOptions, Sandbox, SandboxProvider } from "../types.js";
import { ensureGuestWorkspace, FirecrackerSandbox } from "./sandbox.js";
import { SSH_KEY_PATH, waitForSsh, type SshTarget } from "./ssh.js";
import { bootMicroVm } from "./vm.js";

/** Host tools the provider shells out to for networking and file transfer. */
const REQUIRED_TOOLS = ["ip", "ssh", "tar"];

const SETUP_DOC = "packages/sandbox/README.md";

/**
 * Runs each sandbox as a Firecracker microVM: real kernel-level isolation, at the cost
 * of requiring a Linux host with KVM plus a prepared kernel and rootfs image.
 */
export class FirecrackerProvider implements SandboxProvider {
  readonly name = "firecracker" as const;
  readonly #config: FirecrackerConfig;

  constructor(config: FirecrackerConfig) {
    this.#config = config;
  }

  async ensureAvailable(): Promise<void> {
    const problems = await this.#collectProblems();
    if (problems.length === 0) return;
    throw new Error(
      `The firecracker sandbox provider cannot run on this host:\n${problems
        .map((problem) => `  - ${problem}`)
        .join("\n")}\nSee ${SETUP_DOC} for kernel, rootfs, and network setup.`,
    );
  }

  async create(options: CreateSandboxOptions): Promise<Sandbox> {
    const rootDir = join(WORKSPACES_DIR, options.id);
    const vm = await bootMicroVm({ id: options.id, rootDir, config: this.#config });
    try {
      const target: SshTarget = {
        keyPath: SSH_KEY_PATH,
        host: vm.network.guestIp,
        user: "root",
      };
      await waitForSsh(target);
      await ensureGuestWorkspace(target);
      return new FirecrackerSandbox({ id: options.id, vm, target, env: options.env ?? {}, rootDir });
    } catch (error) {
      await vm.stop();
      await rm(rootDir, { recursive: true, force: true });
      throw error;
    }
  }

  async #collectProblems(): Promise<string[]> {
    const problems: string[] = [];

    if (process.platform !== "linux") {
      problems.push(
        `firecracker needs KVM, which only exists on Linux (this host is ${process.platform}); use the "process" provider or run brevi inside a Linux VM`,
      );
    }
    if (!(await isReadWritable("/dev/kvm"))) {
      problems.push(
        '/dev/kvm is not readable and writable by this user; load the kvm module and add yourself to the "kvm" group',
      );
    }
    if ((await resolveBinary(this.#config.binary)) === undefined) {
      problems.push(
        `the firecracker binary "${this.#config.binary}" was not found on PATH; install it or set sandbox.firecracker.binary`,
      );
    }
    for (const tool of REQUIRED_TOOLS) {
      if ((await resolveBinary(tool)) === undefined) {
        problems.push(`the "${tool}" command was not found on PATH`);
      }
    }
    if (!(await fileExists(this.#config.kernelImage))) {
      problems.push(`kernel image ${this.#config.kernelImage} is missing`);
    }
    if (!(await fileExists(this.#config.rootfs))) {
      problems.push(
        `rootfs image ${this.#config.rootfs} is missing; build it with packages/sandbox/scripts/build-rootfs.sh`,
      );
    }
    if (!(await fileExists(SSH_KEY_PATH))) {
      problems.push(
        `ssh key ${SSH_KEY_PATH} is missing; it is generated by packages/sandbox/scripts/build-rootfs.sh and must match the key baked into the rootfs`,
      );
    }

    return problems;
  }
}
